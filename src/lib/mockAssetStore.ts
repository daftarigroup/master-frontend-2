class MockAssetStore {
  assets: Asset[] = [...initialAssets];
  private nextId = initialAssets.length + 1;

  getAssets(): Asset[] {
    return this.assets;
  }

  getAssetById(id: string): Asset | undefined {
    return this.assets.find((a) => a.id === id);
  }

  createAsset(data: Partial<Asset> & Pick<Asset, 'productName'>): Asset {
    const asset: Asset = {
      id: String(this.nextId++),
      sn: `SN-${String(this.assets.length + 1).padStart(4, '0')}`,
      category: 'IT',
      type: 'Asset',
      brand: '',
      model: '',
      serialNo: '',
      sku: '',
      mfgDate: '',
      origin: '',
      status: 'Active',
      assetDate: new Date().toISOString().slice(0, 10),
      invoiceNo: '',
      cost: 0,
      quantity: 1,
      supplierName: '',
      supplierPhone: '',
      paymentMode: '',
      location: '',
      department: '',
      assignedTo: '',
      responsiblePerson: '',
      warrantyAvailable: 'No',
      warrantyEnd: '',
      amc: 'No',
      amcEnd: '',
      maintenanceRequired: 'No',
      maintenanceType: '',
      frequency: '',
      nextService: '',
      priority: '',
      repairCount: 0,
      lastRepairDate: '',
      repairCost: 0,
      partChanged: 'No',
      partNames: [],
      totalRepairCost: 0,
      assetValue: 0,
      depMethod: 'Straight Line',
      createdBy: 'Admin',
      ...data,
    };
    this.assets = [asset, ...this.assets];
    return asset;
  }

  updateAsset(id: string, data: Partial<Asset>): Asset | undefined {
    let updated: Asset | undefined;
    this.assets = this.assets.map((a) => {
      if (a.id !== id) return a;
      updated = { ...a, ...data };
      return updated;
    });
    return updated;
  }

  deleteAsset(id: string): void {
    this.assets = this.assets.filter((a) => a.id !== id);
  }
}

